/** Devuelve los ids de mascotas que corresponden al progreso actual. */
export function earnedPetIds({ streak, points, totalCompleted }) {
  const value = { streak, points, missions: totalCompleted }
  return PETS.filter((p) => value[p.unlock.type] >= p.unlock.value).map((p) => p.id)
}
